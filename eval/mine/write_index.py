"""Write INDEX.md for the public cases.

usage: write_index.py CASES_DIR [PRIVATE_CASES_DIR]
"""
import json
import sys
from collections import Counter
from pathlib import Path


def load(directory):
    return [json.loads(p.read_text()) for p in sorted(Path(directory).glob("*.json"))]


def visibility(case):
    return ",".join(e["visibility"] for e in case["expected"]) or "-"


def defect(case):
    if case["kind"] == "control":
        return "control: " + case["pr"]["title"]
    return "; ".join(e["description"] for e in case["expected"]).replace("|", "\\|")


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    cases_dir = Path(sys.argv[1])
    cases = load(cases_dir)
    private = load(sys.argv[2]) if len(sys.argv) == 3 and Path(sys.argv[2]).is_dir() else []
    hist = [c for c in cases if c["kind"] == "historical"]
    counts = [
        ("repo", Counter(f"{c['repo'].split('/')[1]} {c['kind']}" for c in cases)),
        ("split", Counter(c["split"] for c in cases)),
        ("visibility", Counter(e["visibility"] for c in hist for e in c["expected"])),
        ("prior bot", Counter(c["prior_bot"]["status"] for c in hist)),
    ]
    lines = [
        "# Eval cases",
        "",
        "Generated by `eval/mine/write_index.py`; do not edit by hand.",
        "",
        f"{len(hist)} historical cases and {len(cases) - len(hist)} controls are public. "
        f"{len(private)} private cases are kept out of version control.",
        "",
    ]
    for name, counter in counts:
        lines.append(f"- {name}: " + ", ".join(f"{k} {v}" for k, v in sorted(counter.items())))
    lines += ["", "| id | kind | split | visibility | prior bot | defect |", "| --- | --- | --- | --- | --- | --- |"]
    for c in cases:
        lines.append(f"| {c['id']} | {c['kind']} | {c['split']} | {visibility(c)} | "
                     f"{c['prior_bot']['status']} | {defect(c)} |")
    (cases_dir / "INDEX.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {cases_dir / 'INDEX.md'}")


if __name__ == "__main__":
    main()
